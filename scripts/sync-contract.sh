#!/usr/bin/env bash
# The app contract has one source, cli/src/annex_cli/contract.md (docs/app-contract.md is a symlink to it).
# Agents also read short copies in skills/annex/SKILL.md and templates/*/AGENTS.md; those carry a generated
# summary (version, core sections, topics) between <!-- contract:begin --> and <!-- contract:end --> markers,
# so they can't drift: the rules themselves are fetched with `annex contract`.
# Usage: scripts/sync-contract.sh          regenerate the summaries
#        scripts/sync-contract.sh --check  exit 1 if any is stale (run by test-all.sh and test-smoke.sh)
source "$(dirname "$0")/lib.sh"
mode=write; [ "${1:-}" = --check ] && mode=check
exec python3 - "$ROOT" "$mode" <<'PY'
import ast, re, sys
from pathlib import Path

root, mode = Path(sys.argv[1]), sys.argv[2]
contract = (root / "cli/src/annex_cli/contract.md").read_text()
version = re.search(r"^ANNEX_CONTRACT_VERSION:\s*(\d+)\s*$", contract, re.M)
if not version:
    sys.exit("cli/src/annex_cli/contract.md has no 'ANNEX_CONTRACT_VERSION: n' line")
# CONTRACT_TOPICS from ops.py, read without importing it (no PyYAML needed)
tree = ast.parse((root / "cli/src/annex_cli/ops.py").read_text())
topics = next(ast.literal_eval(n.value) for n in tree.body
              if isinstance(n, ast.Assign) and getattr(n.targets[0], "id", "") == "CONTRACT_TOPICS")
headings = re.findall(r"^## (.+)$", contract, re.M)
topic_headings = {h for h, _ in topics.values()}
core = [h for h in headings if h not in topic_headings]
lines = [
    "<!-- contract:begin (generated by scripts/sync-contract.sh from cli/src/annex_cli/contract.md; do not edit) -->",
    f"Contract version {version.group(1)} (`ANNEX_CONTRACT_VERSION`). The contract is the authority: `annex contract` "
    "(MCP: `annex_contract`) prints the core, which this file only summarizes.",
    "- Core sections: " + ", ".join(core) + ".",
    "- Topics, fetched only when the app needs them: "
    + "; ".join(f"`annex contract {t}` ({what})" for t, (_, what) in topics.items()) + ".",
    "<!-- contract:end -->",
]
block = "\n".join(lines)
pat = re.compile(r"<!-- contract:begin.*?<!-- contract:end -->", re.S)
files = [root / "skills/annex/SKILL.md", *sorted((root / "templates").glob("*/AGENTS.md"))]
stale = False
for f in files:
    text = f.read_text()
    if not pat.search(text):
        sys.exit(f"{f.relative_to(root)}: no contract:begin / contract:end markers")
    new = pat.sub(lambda _: block, text, count=1)
    if new != text:
        if mode == "check":
            print(f"stale contract summary: {f.relative_to(root)}"); stale = True
        else:
            f.write_text(new); print(f"updated {f.relative_to(root)}")
if mode == "check":
    if stale:
        sys.exit("Run scripts/sync-contract.sh to update them.")
    print("contract summaries: every copy matches contract.md (docs/app-contract.md is a symlink to it)")
PY
