#!/usr/bin/env bash
# The demo client's database (Goat Arcade, D77): a separate compose project on the VM (or the local stack, D99), outside the platform.
# Usage: scripts/democlient.sh up | down | status | check | link [--refresh t[,t]] | dictionary | psql | reseed [--anchor YYYY-MM-DD] [--yes]
#   up      start arcade-db (seeds it on first start)    link        connect product-db to it and (re)apply the views;
#                                                                    --refresh t[,t] after a client table changed shape
#   down    stop it, keep the data                       check       prove the seed's planted stories
#   status  row counts, the anchor date, the link        dictionary  write docs/goat-arcade/data-dictionary.md
#   psql    a psql shell on the client's database        reseed      wipe and seed again: the data then ends
#                                                                    yesterday (or the day before --anchor)
source "$(dirname "$0")/lib.sh"

cmd=${1:-}; shift || true
log "Syncing democlient/ to $DATA/democlient on $WHERE"
rsync -rlpt --delete "$ROOT/democlient/" "$(dest "$DATA/democlient/")"

case "$cmd" in
  up|down|status|check) vm "bash $DATA/democlient/vm.sh $cmd" ;;
  link) vm "bash $DATA/democlient/vm.sh link $*" ;;
  psql) vm_tty "bash $DATA/democlient/vm.sh psql" ;;
  dictionary)
    out=$ROOT/docs/goat-arcade/data-dictionary.md
    mkdir -p "$(dirname "$out")"
    {
      echo "# Goat Arcade data dictionary"
      echo
      echo "Generated by \`scripts/democlient.sh dictionary\` from the comments on the gateway views"
      echo "(\`platform/db/product/clientlink/api_views_arcade.sql\`); edit those, not this file. All data is synthetic."
      echo "The same descriptions are in the gateway's OpenAPI document (\`GET \$ANNEX_GATEWAY_URL/\` with your app's token)."
      echo
      vm "bash $DATA/democlient/vm.sh dictionary"
    } > "$out.tmp"
    mv "$out.tmp" "$out"
    log "Wrote ${out#"$ROOT"/}" ;;
  reseed)
    anchor= yes=
    while [ $# -gt 0 ]; do
      case "$1" in
        --anchor) anchor=${2:?--anchor needs a date, YYYY-MM-DD}; shift 2 ;;
        --yes) yes=1; shift ;;
        *) echo "democlient: unknown option $1" >&2; exit 2 ;;
      esac
    done
    if [ -z "$yes" ]; then
      read -r -p "Wipe Goat Arcade's database on $WHERE and seed it again? [y/N] " a
      [ "$a" = y ] || { echo "democlient: nothing changed"; exit 1; }
    fi
    vm "bash $DATA/democlient/vm.sh reseed $anchor"
    # the link survives a reseed (the foreign tables point at the same names), but check it still answers
    vm "bash $DATA/democlient/vm.sh status" ;;
  *) sed -n '2,8p' "$0" | sed 's/^# \{0,1\}//' >&2; exit 2 ;;
esac
